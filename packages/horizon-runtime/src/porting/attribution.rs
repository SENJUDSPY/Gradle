//! Attribution and licensing compliance generator for the Mod Porting Assistant.
//!
//! Generates structured attribution metadata and human-readable ATTRIBUTION.md files
//! ensuring full legal compliance with original author copyrights and licenses.
//!
//! Copyright (c) 2026 Gradle contributors / Horizon authors (MIT License).

use serde::{Deserialize, Serialize};

/// Attribution manifest detailing original upstream mod details and licensing terms
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AttributionManifest {
    pub original_mod_id: String,
    pub original_mod_name: String,
    pub original_author: String,
    pub upstream_repository_url: String,
    pub upstream_license_spdx: String,
    pub port_author: String,
    pub port_date: String,
    pub derivative_notice: String,
}

impl AttributionManifest {
    /// Formats a complete markdown attribution document
    pub fn to_markdown(&self) -> String {
        format!(
            "# Attribution and Licensing Notice\n\n\
            ## Original Work\n\
            - **Original Mod**: {}\n\
            - **Mod ID**: `{}`\n\
            - **Original Author**: {}\n\
            - **Upstream Repository**: {}\n\
            - **Upstream License**: {}\n\n\
            ## Derivative Port Information\n\
            - **Port Target**: Gradle Horizon Engine (Rust Edition / WebAssembly)\n\
            - **Port Maintainer**: {}\n\
            - **Port Date**: {}\n\n\
            ## License Compliance & Notice\n\
            {}\n\n\
            ---\n\
            *Generated by Gradle Mod Porting Assistant (Version 1.0.4).*",
            self.original_mod_name,
            self.original_mod_id,
            self.original_author,
            self.upstream_repository_url,
            self.upstream_license_spdx,
            self.port_author,
            self.port_date,
            self.derivative_notice
        )
    }
}
